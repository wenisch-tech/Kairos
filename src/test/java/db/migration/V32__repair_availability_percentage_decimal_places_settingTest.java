package db.migration;

import static org.assertj.core.api.Assertions.assertThat;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.util.UUID;

import org.flywaydb.core.api.configuration.Configuration;
import org.flywaydb.core.api.migration.Context;
import org.junit.jupiter.api.Test;

class V32__repair_availability_percentage_decimal_places_settingTest {

    @Test
    void migrateAddsMissingColumnAndBackfillsDefault() throws Exception {
        try (Connection connection = DriverManager.getConnection(h2Url())) {
            connection.createStatement().executeUpdate(
                    "CREATE TABLE resource_type_config ("
                            + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                            + "type_name VARCHAR(255))");
            connection.createStatement().executeUpdate(
                    "INSERT INTO resource_type_config (type_name) VALUES ('HTTP')");

            new V32__repair_availability_percentage_decimal_places_setting()
                    .migrate(context(connection));

            assertThat(columnExists(connection, "resource_type_config", "availability_percentage_decimal_places"))
                    .isTrue();
            try (ResultSet rs = connection.createStatement().executeQuery(
                    "SELECT availability_percentage_decimal_places FROM resource_type_config WHERE type_name = 'HTTP'")) {
                assertThat(rs.next()).isTrue();
                assertThat(rs.getInt(1)).isEqualTo(2);
            }
        }
    }

    @Test
    void migrateNormalizesExistingInvalidValues() throws Exception {
        try (Connection connection = DriverManager.getConnection(h2Url())) {
            connection.createStatement().executeUpdate(
                    "CREATE TABLE resource_type_config ("
                            + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                            + "type_name VARCHAR(255), "
                            + "availability_percentage_decimal_places INT)");
            connection.createStatement().executeUpdate(
                    "INSERT INTO resource_type_config (type_name, availability_percentage_decimal_places) "
                            + "VALUES ('HTTP', 1), ('TCP', 4), ('DOCKER', NULL)");

            new V32__repair_availability_percentage_decimal_places_setting()
                    .migrate(context(connection));

            try (ResultSet rs = connection.createStatement().executeQuery(
                    "SELECT type_name, availability_percentage_decimal_places FROM resource_type_config ORDER BY type_name")) {
                assertThat(rs.next()).isTrue();
                assertThat(rs.getString(1)).isEqualTo("DOCKER");
                assertThat(rs.getInt(2)).isEqualTo(2);
                assertThat(rs.next()).isTrue();
                assertThat(rs.getString(1)).isEqualTo("HTTP");
                assertThat(rs.getInt(2)).isEqualTo(2);
                assertThat(rs.next()).isTrue();
                assertThat(rs.getString(1)).isEqualTo("TCP");
                assertThat(rs.getInt(2)).isEqualTo(4);
                assertThat(rs.next()).isFalse();
            }
        }
    }

    private static Context context(Connection connection) {
        return new Context() {
            @Override
            public Configuration getConfiguration() {
                return null;
            }

            @Override
            public Connection getConnection() {
                return connection;
            }
        };
    }

    private static String h2Url() {
        return "jdbc:h2:mem:" + UUID.randomUUID() + ";MODE=PostgreSQL";
    }

    private static boolean columnExists(Connection connection, String tableName, String columnName) throws Exception {
        try (ResultSet rs = connection.getMetaData()
                .getColumns(null, null, tableName.toUpperCase(), columnName.toUpperCase())) {
            return rs.next();
        }
    }
}